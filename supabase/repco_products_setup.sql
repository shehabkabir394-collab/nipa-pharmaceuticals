-- Run once in the existing Supabase project: Dashboard > SQL Editor.
-- IDs start above the 85 built-in product IDs.
create table if not exists public.repco_products (
  id bigint generated by default as identity (start with 1000000) primary key,
  code text unique,
  name text not null check (char_length(name) between 1 and 120),
  generic_name text not null check (char_length(generic_name) between 1 and 180),
  pack_size text not null check (char_length(pack_size) between 1 and 80),
  fixed_price numeric(12,2) not null check (fixed_price >= 0),
  mrp numeric(12,2) not null check (mrp >= 0),
  category text not null,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);
alter table public.repco_products enable row level security;
drop policy if exists "Authenticated users can view Repco products" on public.repco_products;
create policy "Authenticated users can view Repco products" on public.repco_products
  for select to authenticated using (exists (
    select 1 from public.profiles p where p.id=(select auth.uid()) and p.active=true
  ));
drop policy if exists "Admins can add Repco products" on public.repco_products;
create policy "Admins can add Repco products" on public.repco_products
  for insert to authenticated with check (
    created_by=(select auth.uid()) and exists (
      select 1 from public.profiles p
      where p.id=(select auth.uid()) and p.active=true and p.role='admin'
    )
  );
grant select, insert on public.repco_products to authenticated;
grant usage, select on sequence public.repco_products_id_seq to authenticated;
comment on table public.repco_products is 'Additional Rephco products created by authorized app admins.';
